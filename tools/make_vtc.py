#!/usr/bin/env python3
"""Generate out/cat_claims.vtc from out/tokens.json.

Only tokens that passed tools/validate.py are emitted (reads out/report.json).

Assertions are emitted only where the expected access result is definite (accept/reject)
and the request context can be expressed in a plain-HTTP varnishtest client. Everything
else is emitted as a commented-out block that states why it is skipped:
  * undefined      - spec leaves the result to the recipient
  * probabilistic  - catpor 0 < p < 1 needs a statistical run
  * needs TLS      - ALPN, client certificate or TLS fingerprint context (catalpn, cattpk,
                     catnetprint); engineers decide how to supply this (see README)
catr renewal expectations are written as comments next to the access assertion.

Usage: tools/make_vtc.py [--harness vtc/harness_template.vcl]
"""

import argparse
import json
import os
import sys
from urllib.parse import urlsplit

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from catcheck import manifest  # noqa: E402

RUNNABLE_NEEDS = {"plaintext"}  # varnishtest clients speak plain HTTP


def request_lines(t):
    req = t["request"]
    tok = t["token_b64url"]
    u = urlsplit(req["url"])
    path = u.path + ("?" + u.query if u.query else "")
    hdrs = ['"Host: %s"' % u.netloc, '"cat-test-id: %s"' % t["id"]]
    loc = req["token_location"]
    if loc == "header":
        hdrs.append('"%s: %s"' % (req["token_name"], tok))
    elif loc == "cookie":
        hdrs.append('"Cookie: %s=%s"' % (req["token_name"], tok))
    elif loc == "uri":
        if tok not in path:
            raise ValueError("%s: uri token location but token not in URL" % t["id"])
    else:
        raise ValueError(loc)
    lines = ["\ttxreq -req %s -url \"%s\" \\" % (req["method"], path)]
    for i, h in enumerate(hdrs):
        lines.append("\t\t-hdr %s%s" % (h, " \\" if i < len(hdrs) - 1 else ""))
    return lines


def case_lines(t):
    """Request + assertions. cti_seen_before cases send the same token twice and assert both."""
    e = t["expected"]
    one = request_lines(t) + ["\trxresp", "\texpect resp.http.cat-test-id == \"%s\"" % t["id"],
                              "\texpect resp.http.cat-result == \"%s\"" % e["access"]]
    rd = e.get("renewal_decision")
    req = t["request"]
    if rd == "MUST NOT renew" and e["access"] == "accept":
        # Nothing may convey a renewed token: no Set-Cookie, no renewal header, no redirect.
        one += ["\t# MUST NOT renew: no renewed token in the response",
                "\texpect resp.http.Set-Cookie == <undef>",
                "\texpect resp.http.Location == <undef>",
                "\texpect resp.http.CTA-Common-Access-Token == <undef>"]
    elif rd in ("SHOULD renew", "MAY renew"):
        conv = []
        r = t.get("_renewal") or {}
        if r.get("conveyance") == "cookie":
            conv.append("expect resp.http.Set-Cookie ~ \"^%s=\"" % r["cookie_name"])
        elif r.get("conveyance") == "header":
            conv.append("expect resp.http.%s != <undef>" % r["header_name"])
        elif r.get("conveyance") == "redirect":
            conv.append("expect resp.status == %d" % r["status"])
        one += ["\t# %s (not asserted: SHOULD/MAY). If the service renews, expect:" % rd] + \
               ["\t#   " + c for c in conv] + \
               ["\t#   and check the renewed token with: tools/check_renewed.py %s <renewed-token>" % t["id"]]
    if req.get("cti_seen_before"):
        first = request_lines(t) + ["\trxresp", "\t# first use (replay test setup)"]
        return first + one
    return one


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--harness", default=os.path.join(manifest.ROOT, "vtc", "harness_template.vcl"))
    args = ap.parse_args()
    root = manifest.ROOT
    doc = json.load(open(os.path.join(root, "out", "tokens.json")))
    rep = json.load(open(os.path.join(root, "out", "report.json")))
    passed = {r["id"] for r in rep["results"] if r["ok"]}
    renewal_by_id = {r["id"]: r["evaluator"].get("renewal") for r in rep["results"]}
    for t in doc["tokens"]:
        t["_renewal"] = renewal_by_id.get(t["id"])
    if rep["failures"] or len(passed) != doc["count"]:
        print("refusing: out/report.json has failures or is stale; run tools/validate.py")
        sys.exit(1)
    kid, key = manifest.load_key()
    import base64
    harness = open(args.harness).read().replace("@@KID@@", kid).replace("@@KEY_B64@@", base64.b64encode(key).decode())

    out = ['varnishtest "CAT claim test vectors (generated by tools/make_vtc.py - do not edit)"', "",
           "# Source: out/tokens.json (%d tokens, all passed tools/validate.py)." % doc["count"],
           "# Expected results come from cases/*.json; see each case's spec_ref and basis.", "",
           "varnish v1 -vcl {", harness.rstrip("\n"), "} -start", "", "client c1 {"]
    stats = {"asserted": 0, "skipped": 0}
    for t in doc["tokens"]:
        e = t["expected"]
        why = None
        if e["access"] == "undefined":
            why = "expected result undefined (%s)" % e["basis"]
        elif e["access"] == "probabilistic":
            why = "probabilistic: rejection probability %s - run statistically" % e["probability_of_rejection"]
        elif set(t["needs"]) - RUNNABLE_NEEDS:
            why = "needs %s context, not expressible in a plain varnishtest client" % ", ".join(sorted(set(t["needs"]) - RUNNABLE_NEEDS))
        out.append("")
        out.append("\t# %s - %s" % (t["id"], t["title"]))
        out.append("\t# expected: %s  [%s, %s]  %s" % (e["access"], e["basis"], e["spec_ref"], e["reason"]))
        out.append("\t# claims: %s" % (t["claims_edn"] if len(t["claims_edn"]) < 400 else t["claims_edn"][:400] + " ..."))
        if t["needs"]:
            out.append("\t# request context: %s" % json.dumps(t["request"].get("tls")))
        if "renewal_decision" in e:
            out.append("\t# catr renewal expectation: %s" % e["renewal_decision"])
        lines = case_lines(t)
        if why:
            stats["skipped"] += 1
            out.append("\t# SKIPPED: %s" % why)
            out.extend("\t# " + l.lstrip("\t") for l in lines)
        else:
            stats["asserted"] += 1
            out.extend(lines)
    out += ["} -run", ""]
    path = os.path.join(root, "out", "cat_claims.vtc")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print("wrote %s: %d asserted, %d skipped (commented with reason)" % (os.path.relpath(path, root), stats["asserted"], stats["skipped"]))


if __name__ == "__main__":
    main()
