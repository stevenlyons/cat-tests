#!/usr/bin/env python3
"""Generate signed CAT test tokens from cases/*.json  ->  out/tokens.json

Each output entry documents the case in JSON: the full claim set in CBOR diagnostic
notation (claims_edn) and as typed JSON (claims_typed), the request context, the expected
result with its spec basis, and the token itself (token_b64url / token_hex).

Tokens are CWT/COSE_Mac0, HMAC 256/256, signed with keys/hs256-test-key.json (TEST ONLY).
"""

import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from catcheck import cbor, cose, manifest  # noqa: E402


def main():
    kid, key = manifest.load_key()
    spki = manifest.load_spki()
    problems, out = [], []
    for meta, case in manifest.load_cases():
        errs = manifest.check_case_fields(case, meta["claim_key"])
        if errs:
            problems.append("%s: %s" % (case.get("id"), "; ".join(errs)))
            continue
        claims = manifest.full_claims(case, spki)
        token = cose.build_mac0(claims, key, kid)
        b64 = cose.b64url_encode(token)
        req = manifest.request_for(case)
        req["url"] = req["url"].replace("${token}", b64)
        out.append({
            "id": case["id"],
            "claim": meta["claim"],
            "claim_key": meta["claim_key"],
            "ticket": meta["ticket"],
            "title": case["title"],
            "category": case["category"],
            "expected": case["expected"],
            "request": req,
            "needs": case.get("needs", []),
            "notes": case.get("notes"),
            "header": {"protected_edn": "{1: 5, 4: %s}" % json.dumps(kid), "unprotected_edn": "{}",
                       "outer_tags": [cose.TAG_CWT, cose.TAG_COSE_MAC0]},
            "claims_edn": cbor.to_edn(claims),
            "claims_typed": cbor.to_typed_json(claims),
            "token_b64url": b64,
            "token_hex": token.hex(),
            "token_bytes": len(token),
        })
    if problems:
        print("Manifest problems:\n  " + "\n  ".join(problems))
        sys.exit(1)
    os.makedirs(os.path.join(manifest.ROOT, "out"), exist_ok=True)
    doc = {"_comment": "Generated by tools/generate.py from cases/*.json. Do not edit by hand.",
           "kid": kid, "key_file": "keys/hs256-test-key.json", "count": len(out), "tokens": out}
    path = os.path.join(manifest.ROOT, "out", "tokens.json")
    with open(path, "w") as f:
        json.dump(doc, f, indent=2, ensure_ascii=False)
    print("wrote %d tokens to %s" % (len(out), os.path.relpath(path, manifest.ROOT)))


if __name__ == "__main__":
    main()
